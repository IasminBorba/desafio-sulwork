-- =====================================================================
-- Catálogos (populados por seed)
-- =====================================================================

CREATE TABLE categoria (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    CONSTRAINT uk_categoria_nome UNIQUE (nome)
);

CREATE TABLE alergeno (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    CONSTRAINT uk_alergeno_nome UNIQUE (nome)
);

CREATE TABLE restricao_alimentar (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    CONSTRAINT uk_restricao_alimentar_nome UNIQUE (nome)
);

CREATE TABLE restricao_alergeno (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restricao_id BIGINT NOT NULL,
    alergeno_id  BIGINT NOT NULL,
    CONSTRAINT uk_restricao_alergeno UNIQUE (restricao_id, alergeno_id),
    CONSTRAINT fk_restricao_alergeno_restricao FOREIGN KEY (restricao_id)
        REFERENCES restricao_alimentar (id) ON DELETE CASCADE,
    CONSTRAINT fk_restricao_alergeno_alergeno FOREIGN KEY (alergeno_id)
        REFERENCES alergeno (id) ON DELETE CASCADE
);

CREATE INDEX idx_restricao_alergeno_alergeno ON restricao_alergeno (alergeno_id);

-- =====================================================================
-- Usuários
-- =====================================================================

CREATE TABLE usuario (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(150) NOT NULL,
    cpf           CHAR(11)     NOT NULL,
    email         VARCHAR(255) NOT NULL,
    senha_hash    VARCHAR(100) NOT NULL,
    criado_em     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_usuario_cpf UNIQUE (cpf),
    CONSTRAINT uk_usuario_email UNIQUE (email),
    CONSTRAINT ck_usuario_cpf_formato CHECK (cpf ~ '^[0-9]{11}$')
);

CREATE TABLE usuario_restricao (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id   BIGINT NOT NULL,
    restricao_id BIGINT NOT NULL,
    CONSTRAINT uk_usuario_restricao UNIQUE (usuario_id, restricao_id),
    CONSTRAINT fk_usuario_restricao_usuario FOREIGN KEY (usuario_id)
        REFERENCES usuario (id) ON DELETE CASCADE,
    CONSTRAINT fk_usuario_restricao_restricao FOREIGN KEY (restricao_id)
        REFERENCES restricao_alimentar (id)
);

CREATE INDEX idx_usuario_restricao_restricao ON usuario_restricao (restricao_id);

-- =====================================================================
-- Eventos
-- =====================================================================

CREATE TABLE evento (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(150) NOT NULL,
    descricao       TEXT,
    tipo            VARCHAR(30)  NOT NULL,
    data_inicio     TIMESTAMPTZ  NOT NULL,
    data_fim        TIMESTAMPTZ  NOT NULL,
    prazo_alteracao TIMESTAMPTZ  NOT NULL,
    status          VARCHAR(20)  NOT NULL DEFAULT 'RASCUNHO',
    organizador_id  BIGINT       NOT NULL,
    criado_em       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_evento_organizador FOREIGN KEY (organizador_id) REFERENCES usuario (id),
    CONSTRAINT ck_evento_datas CHECK (data_fim >= data_inicio),
    CONSTRAINT ck_evento_prazo CHECK (prazo_alteracao <= data_inicio),
    CONSTRAINT ck_evento_status CHECK (status IN ('RASCUNHO', 'ABERTO', 'ENCERRADO', 'REALIZADO', 'CANCELADO')),
    CONSTRAINT ck_evento_tipo CHECK (tipo IN ('CHURRASCO', 'ALMOCO', 'JANTAR', 'CAFE_DA_MANHA', 'LANCHE',
                                              'FEIJOADA', 'PIQUENIQUE', 'FESTA_TEMATICA', 'CONFRATERNIZACAO', 'OUTRO'))
);

CREATE INDEX idx_evento_organizador ON evento (organizador_id);

-- Encerramento lazy: o UPDATE por prazo vencido só olha eventos abertos.
CREATE INDEX idx_evento_prazo_aberto ON evento (prazo_alteracao) WHERE status = 'ABERTO';

CREATE TABLE participacao (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    evento_id  BIGINT NOT NULL,
    CONSTRAINT uk_participacao_usuario_evento UNIQUE (usuario_id, evento_id),
    CONSTRAINT fk_participacao_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT fk_participacao_evento FOREIGN KEY (evento_id) REFERENCES evento (id)
);

CREATE INDEX idx_participacao_evento ON participacao (evento_id);

-- =====================================================================
-- Itens, metas e contribuições
-- =====================================================================

CREATE TABLE item (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id             BIGINT       NOT NULL,
    categoria_id          BIGINT       NOT NULL,
    nome                  VARCHAR(150) NOT NULL,
    quantidade_necessaria INTEGER      NOT NULL,
    obrigatorio           BOOLEAN      NOT NULL DEFAULT FALSE,
    criado_em             TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_item_evento FOREIGN KEY (evento_id) REFERENCES evento (id),
    CONSTRAINT fk_item_categoria FOREIGN KEY (categoria_id) REFERENCES categoria (id),
    CONSTRAINT ck_item_quantidade_necessaria CHECK (quantidade_necessaria > 0)
);

CREATE INDEX idx_item_evento_categoria ON item (evento_id, categoria_id);
CREATE INDEX idx_item_categoria ON item (categoria_id);

CREATE TABLE item_alergeno (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id     BIGINT NOT NULL,
    alergeno_id BIGINT NOT NULL,
    CONSTRAINT uk_item_alergeno UNIQUE (item_id, alergeno_id),
    CONSTRAINT fk_item_alergeno_item FOREIGN KEY (item_id) REFERENCES item (id) ON DELETE CASCADE,
    CONSTRAINT fk_item_alergeno_alergeno FOREIGN KEY (alergeno_id) REFERENCES alergeno (id)
);

CREATE INDEX idx_item_alergeno_alergeno ON item_alergeno (alergeno_id);

CREATE TABLE meta_categoria (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id       BIGINT      NOT NULL,
    categoria_id    BIGINT      NOT NULL,
    quantidade_meta INTEGER     NOT NULL,
    criado_em       TIMESTAMPTZ NOT NULL DEFAULT now(),
    atualizado_em   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_meta_categoria_evento_categoria UNIQUE (evento_id, categoria_id),
    CONSTRAINT fk_meta_categoria_evento FOREIGN KEY (evento_id) REFERENCES evento (id),
    CONSTRAINT fk_meta_categoria_categoria FOREIGN KEY (categoria_id) REFERENCES categoria (id),
    CONSTRAINT ck_meta_categoria_quantidade CHECK (quantidade_meta > 0)
);

CREATE INDEX idx_meta_categoria_categoria ON meta_categoria (categoria_id);

CREATE TABLE contribuicao (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participacao_id BIGINT      NOT NULL,
    item_id         BIGINT      NOT NULL,
    quantidade      INTEGER     NOT NULL,
    criado_em       TIMESTAMPTZ NOT NULL DEFAULT now(),
    atualizado_em   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_contribuicao_participacao_item UNIQUE (participacao_id, item_id),
    -- P11: cancelar a participação apaga as contribuições da pessoa.
    CONSTRAINT fk_contribuicao_participacao FOREIGN KEY (participacao_id)
        REFERENCES participacao (id) ON DELETE CASCADE,
    CONSTRAINT fk_contribuicao_item FOREIGN KEY (item_id) REFERENCES item (id),
    CONSTRAINT ck_contribuicao_quantidade CHECK (quantidade > 0)
);

CREATE INDEX idx_contribuicao_item ON contribuicao (item_id);
